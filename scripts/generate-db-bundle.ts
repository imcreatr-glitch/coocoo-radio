/**
 * Snapshots db/custom.db into src/lib/db-bundle.ts (base64) so that serverless
 * bundles (Netlify) always ship a seeded database, even if file tracing misses
 * the SQLite file inside the lambda bundle.
 *
 * Run after every db:push / seed / admin-password change:
 *   bun scripts/generate-db-bundle.ts
 */
import fs from "fs";
import path from "path";
import crypto from "crypto";

const root = process.cwd();
const dbPath = path.join(root, "db", "custom.db");
const outPath = path.join(root, "src", "lib", "db-bundle.ts");

if (!fs.existsSync(dbPath)) {
  console.error(`Database not found at ${dbPath} — run 'bun run db:push && bun scripts/seed.ts' first.`);
  process.exit(1);
}

const buf = fs.readFileSync(dbPath);
const b64 = buf.toString("base64");
const sha = crypto.createHash("sha256").update(buf).digest("hex");

const chunks: string[] = [];
for (let i = 0; i < b64.length; i += 2000) chunks.push(b64.slice(i, i + 2000));

const body = `// AUTO-GENERATED by scripts/generate-db-bundle.ts — do not edit by hand.
// Base64 snapshot of db/custom.db (sha256 ${sha})
// Regenerate with: bun scripts/generate-db-bundle.ts
export const BUNDLED_DB_SHA256 = "${sha}";
export const BUNDLED_DB_B64 = [
${chunks.map((c) => `  "${c}",`).join("\n")}
].join("");
`;

fs.writeFileSync(outPath, body);
console.log(
  `db-bundle.ts written: ${(b64.length / 1024).toFixed(1)} KB base64 from ${(buf.length / 1024).toFixed(1)} KB db, sha256 ${sha.slice(0, 12)}...`
);
